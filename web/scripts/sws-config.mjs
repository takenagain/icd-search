// Writes docker/sws.toml = docker/sws.base.toml + one immutable-cache rule per hashed file in dist/.
// usage: node scripts/sws-config.mjs   (run after the site build; part of `npm run build`)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dist = resolve(root, 'dist');
const IMMUTABLE = 'public, max-age=31536000, immutable';
const plain = (f) => !/\.(br|gz)$/.test(f);

const rules = [];
for (const f of readdirSync(resolve(dist, 'assets')).filter(plain).sort()) {
  rules.push({ source: `/assets/${f}`, headers: { 'Cache-Control': IMMUTABLE } });
}
for (const f of readdirSync(resolve(dist, 'data')).filter(plain).sort()) {
  if (!/^shard-\d+\.[0-9a-f]{10}\.ndjson$/.test(f)) continue;
  rules.push({ source: `/data/${f}`, headers: { 'Cache-Control': IMMUTABLE, 'Content-Type': 'application/x-ndjson' } });
}
if (!rules.length) throw new Error('dist/ has no assets: build the site first');

const q = (s) => JSON.stringify(s);
let out = readFileSync(resolve(root, 'docker/sws.base.toml'), 'utf8').trimEnd() + '\n\n';
out += '# ---- Generated by web/scripts/sws-config.mjs: one rule per hashed file of this build -----------\n';
for (const r of rules) {
  out += `\n[[advanced.headers]]\nsource = ${q(r.source)}\nheaders = { ${Object.entries(r.headers).map(([k, v]) => `${k} = ${q(v)}`).join(', ')} }\n`;
}
writeFileSync(resolve(root, 'docker/sws.toml'), out);
console.log(`docker/sws.toml: ${rules.length} immutable rules`);
